#!/usr/bin/env python3
"""Generate src/catalog.h from the JSON written by tools/collectibles.py --json."""
import json
import sys
from pathlib import Path

CATEGORIES = ["MANUSCRIPTPAGES", "THERMOS", "CANPYRAMIDS", "CHESTS", "RADIOSHOWS", "TVSHOWS",
              "SIGNS", "DLC1_ALARMCLOCKS", "DLC1_CARDBOARDCUTOUTS",
              "DLC2_NIGHTSPRINGSVIDEOGAMES"]

rows = json.loads(Path(sys.argv[1]).read_text())
items = sorted((int(r["level"].split("_")[1]), CATEGORIES.index(r["category"]), r["number"],
                int(r["nightmare"])) for r in rows
               # other categories (coconut songs come with any playthrough) are not shown
               if r["category"] in CATEGORIES)
lines = ["/* Generated by gen_catalog.py: where every collectible is. Do not edit. */",
         "static const struct item CATALOG[] = {"]
lines += [f"    {{{level}, {category}, {number}, {hard}}},"
          for level, category, number, hard in items]
lines.append("};")

# names as the game shows them, in English
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from collectibles import DEFAULT_DATA, Archives, episodes  # noqa: E402

names = episodes(Archives(DEFAULT_DATA), "en")
lines += ["", "static const struct level_name LEVEL_NAMES[] = {"]
for level, ((episode, _), title, chapter) in sorted(names.items(), key=lambda n: int(n[0][6:])):
    # the special episodes come with a "DLC n: " prefix on top of the game's own name
    heading = title if episode <= 6 else title.split(": ", 1)[1]
    lines.append(f"    {{{int(level[6:])}, {json.dumps(heading)}, {json.dumps(chapter)}}},")
lines.append("};")
(Path(__file__).parent / "src" / "catalog.h").write_text("\n".join(lines) + "\n")
print(len(items), "items")
