#!/usr/bin/env python3
"""Generate src/catalog.h from the JSON written by tools/collectibles.py --json."""
import collections
import json
import re
import sys
from pathlib import Path

CATEGORIES = ["MANUSCRIPTPAGES", "THERMOS", "CANPYRAMIDS", "CHESTS", "RADIOSHOWS", "TVSHOWS",
              "SIGNS", "DLC1_ALARMCLOCKS", "DLC1_CARDBOARDCUTOUTS",
              "DLC2_NIGHTSPRINGSVIDEOGAMES"]

# Where a few items are, from the developers' names for the level scripts that hand them out.
# Not checked in game.
HINTS = {
    "CHESTS": {5: "Moonshine Cave", 6: "Lover's Peak", 7: "plane", 13: "hidden cave",
               16: "hunting cabin", 17: "woods", 18: "barn", 19: "streets", 20: "fishers",
               21: "town hall", 22: "bookstore", 23: "transformers", 24: "helicopter",
               25: "helicopter"},
    "SIGNS": {2: "missing persons", 4: "Moonshine Cave", 5: "Great Old One", 6: "tree slice",
              10: "sundial", 11: "lodge sign", 12: "book poster", 13: "statue",
              15: "outside the junkyard", 16: "junkyard office", 17: "park", 18: "bookstore",
              19: "church", 24: "motel advert", 25: "motel"},
}

# Item numbers in the order they are found, where that is not the numbers' order (seen in game).
ORDER = {"DLC1_CARDBOARDCUTOUTS": [6, 3, 2, 4, 5, 1]}

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from collectibles import DEFAULT_DATA, Archives, episodes, string_table  # noqa: E402

game = Archives(DEFAULT_DATA)
strings = string_table(game, "en")


def c_string(text):
    # the mod draws and widens text byte by byte, so keep it ASCII
    text = text.replace("\u2019", "'")
    if not text.isascii():
        raise SystemExit(f"not ASCII: {text!r}")
    return json.dumps(text)


rows = json.loads(Path(sys.argv[1]).read_text())
# other categories (coconut songs come with any playthrough) are not shown
rows = sorted((r for r in rows if r["category"] in CATEGORIES),
              key=lambda r: (int(r["level"].split("_")[1]), CATEGORIES.index(r["category"]),
                             ORDER[r["category"]].index(r["number"])
                             if r["category"] in ORDER else r["number"]))
lines = ["/* Generated by gen_catalog.py: where every collectible is. Do not edit. */",
         "static const struct item CATALOG[] = {"]
seen = collections.Counter()
for r in rows:
    level, category = int(r["level"].split("_")[1]), CATEGORIES.index(r["category"])
    seen[level, category] += 1
    if r["category"] == "MANUSCRIPTPAGES":
        # pages carry their own number within the chapter, and a title
        shown, text = int(r["label"].rsplit("_", 1)[1]), strings[r["label"]]
    else:
        shown = seen[level, category]
        text = HINTS.get(r["category"], {}).get(r["number"])
    if r["category"] == "DLC1_CARDBOARDCUTOUTS":
        # the name heading the text shown when examining it, e.g. string `cutout_barry`
        key = re.search(r"cutout_(?!usable)[a-z]+", " ".join(r["objects"]))[0]
        text = strings[key].split("\\n")[0].title()
    lines.append(f"    {{{level}, {category}, {r['number']}, {int(r['nightmare'])}, {shown}, "
                 f"{c_string(text) if text else 'NULL'}}},")
lines.append("};")

# names as the game shows them, in English
names = episodes(game, "en")
lines += ["", "static const struct level_name LEVEL_NAMES[] = {"]
for level, ((episode, _), title, chapter) in sorted(names.items(), key=lambda n: int(n[0][6:])):
    # the special episodes come with a "DLC n: " prefix on top of the game's own name
    heading = title if episode <= 6 else title.split(": ", 1)[1]
    lines.append(f"    {{{int(level[6:])}, {c_string(heading)}, {c_string(chapter)}}},")
lines.append("};")
(Path(__file__).parent / "src" / "catalog.h").write_text("\n".join(lines) + "\n")
print(len(rows), "items")
